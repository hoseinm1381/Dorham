"""Generate the Go bootstrap DDL from the preserved pre-Go migrations.

Only literal DDL is shared. Runtime migrations and database handling are Go.
Review the generated file when changing the historical schema.
"""
from pathlib import Path
import re, json
root=Path(__file__).resolve().parent.parent
base=(root/'apps/api/src/db.ts').read_text(encoding='utf8').split('const schema = [',1)[1].split('\n];',1)[0]
queries=re.findall(r'`([^`]+)`',base)
assert len(queries)==26, len(queries)
migrations=(root/'apps/api/src/migrations.ts').read_text(encoding='utf8')
parts=re.split(r"if \(await tx.one\('SELECT version FROM schema_migrations WHERE version=(\d+)'\)\) return;",migrations)
expansion={}
for i in range(1,len(parts),2):
    version=int(parts[i]);text=parts[i+1];ddl=[]
    for m in re.finditer(r'''(['"])((?:ALTER TABLE|CREATE TABLE|CREATE INDEX)[^\n]*?)\1''',text):
        ddl.append(m.group(2))
    expansion[version]=ddl
assert sorted(expansion)==list(range(2,12))
out=['// Code generated by scripts/go-schema.py from historical TS DDL; DO NOT EDIT.','package backend','','var baseSchema = []string{']
out += ['\t'+json.dumps(q,ensure_ascii=False)+',' for q in queries]
out += ['}','', 'var expansionSchema = map[int][]string{']
for version,ddl in expansion.items():
    out.append(f'\t{version}: {{')
    out += ['\t\t'+json.dumps(q,ensure_ascii=False)+',' for q in ddl]
    out.append('\t},')
out += ['}', '']
(root/'apps/api-go/internal/backend/schema_sql.go').write_text('\n'.join(out),encoding='utf8')
print(json.dumps({'baseStatements':len(queries),'migrationStatements':{v:len(q) for v,q in expansion.items()}}))
